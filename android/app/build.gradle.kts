val launcherName = (findProperty("purse.appName") as String?)?.takeIf { it.isNotBlank() } ?: "Purse"

android {
    namespace = "app.purse"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.purse"
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
        resValue("string", "app_name", launcherName)
    }

    // Release signing comes from the environment (see README); without it the
    // release build falls back to the debug key so it is still installable.
    val keystore = System.getenv("PURSE_KEYSTORE")?.let { file(it) }?.takeIf { it.exists() }
    signingConfigs {
        if (keystore != null) {
            create("release") {
                storeFile = keystore
                storePassword = System.getenv("PURSE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("PURSE_KEY_ALIAS")
                keyPassword = System.getenv("PURSE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += setOf(
                "/META-INF/{AL2.0,LGPL2.1}",
                "META-INF/DEPENDENCIES",
                "META-INF/LICENSE*",
                "META-INF/NOTICE*",
                "META-INF/*.SF",
                "META-INF/*.RSA",
                "META-INF/*.DSA",
                "plugin.properties",
                "about.html",
            )
        }
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }
}

